// Same pure money/payment/recurrence rules in Next and PocketBase; no duplicate financial formulas.
import ts from '../app/node_modules/typescript/lib/typescript.js';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const modules = {
 'money': 'lib/money',
 'journal-invariants': 'modules/journal/invariants',
 'sales-invariants': 'modules/sales/invariants',
 'payment-invariants': 'modules/payments/invariants',
 'recurring-invariants': 'modules/sales/wiederkehrend-invariants',
};
const dir = new URL('../pocketbase/pb_hooks/domain/', import.meta.url);
if (!process.argv.includes('--check')) mkdirSync(dir, { recursive: true });
for (const [name, source] of Object.entries(modules)) {
 let output = '// GENERATED by node scripts/build-finanz-domain-hook.mjs. Do not edit.\n' + ts.transpileModule(readFileSync(new URL('../app/src/'+source+'.ts', import.meta.url),'utf8'), { compilerOptions: {target:ts.ScriptTarget.ES2017,module:ts.ModuleKind.CommonJS,esModuleInterop:true} }).outputText;
 for (const [target,path] of Object.entries(modules)) output=output.replaceAll('require("@/'+path+'")','require("./'+target+'.js")');
 output=output.replaceAll('require("./invariants")','require("./sales-invariants.js")').replaceAll('require("decimal.js")','require("../vendor/decimal.js")');
 if (/require\("@\//.test(output)) throw new Error('Unmapped runtime dependency: '+source);
 const dest=new URL(name+'.js',dir);
 if (process.argv.includes('--check')) { if(readFileSync(dest,'utf8')!==output) throw new Error('Stale generated hook: '+name); }
 else writeFileSync(dest,output);
}
